// background.js - Daisy Safari Extension

const _api = typeof browser !== "undefined" ? browser : chrome;

let dispatchEnabled = true;
let bypassNextDownloadUrl = null;

_api.storage.local.get(["dispatchEnabled"]).then(res => {
    if (typeof res.dispatchEnabled === "boolean") dispatchEnabled = res.dispatchEnabled;
});

_api.storage.onChanged.addListener((changes, area) => {
    if (area === "local" && changes.dispatchEnabled) {
        dispatchEnabled = changes.dispatchEnabled.newValue;
        // Sync to native app
        fetch(`http://127.0.0.1:6840/setenabled`, {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({ enabled: changes.dispatchEnabled.newValue })
        }).catch(() => {});
    }
});

_api.runtime.onInstalled.addListener(() => {
    _api.contextMenus.create({ id: "dispatch-download", title: "Download with Daisy", contexts: ["link"] });
});

_api.contextMenus.onClicked.addListener((info, tab) => {
    if (info.menuItemId === "dispatch-download" && info.linkUrl) {
        triggerDownload(info.linkUrl, extractFilename(info.linkUrl), tab?.url || "");
    }
});

function extractFilename(url) {
    try {
        const parts = new URL(url).pathname.split("/");
        return decodeURIComponent(parts[parts.length - 1]) || "download";
    } catch { return "download"; }
}

function needsCredentialedFetch(url) {
    try { return /claude\.ai$/.test(new URL(url).hostname); } catch { return false; }
}

function formatNetscapeCookies(cookies) {
    let output = "# Netscape HTTP Cookie File\n# Generated by Daisy\n\n";
    let uniqueCookies = new Map();
    for (let c of cookies) {
        uniqueCookies.set(`${c.domain}:${c.name}`, c);
    }
    for (let c of uniqueCookies.values()) {
        let domain = c.domain;
        let includeSubdomains = domain.startsWith('.') ? "TRUE" : "FALSE";
        let path = c.path;
        let secure = c.secure ? "TRUE" : "FALSE";
        let expiration = c.expirationDate ? Math.round(c.expirationDate) : Math.round(Date.now() / 1000) + 3600;
        output += `${domain}\t${includeSubdomains}\t${path}\t${secure}\t${expiration}\t${c.name}\t${c.value}\n`;
    }
    return output;
}

async function fetchBaseDomainCookies(targetUrl) {
    return new Promise(resolve => {
        try {
            let urlObj = new URL(targetUrl);
            let hostParts = urlObj.hostname.split('.');
            let baseDomain = hostParts.length > 2 ? hostParts.slice(-2).join('.') : urlObj.hostname;
            _api.cookies.getAll({ domain: baseDomain }, cookies => {
                if (cookies && cookies.length > 0) {
                    resolve(formatNetscapeCookies(cookies));
                } else {
                    resolve("");
                }
            });
        } catch {
            resolve("");
        }
    });
}

async function getYouTubeAuthCookies() {
    return new Promise(resolve => {
        _api.cookies.getAll({ domain: "youtube.com" }, yt => {
            _api.cookies.getAll({ domain: "google.com" }, gl => {
                resolve([...(yt || []), ...(gl || [])]);
            });
        });
    });
}

_api.runtime.onMessage.addListener((message, sender, sendResponse) => {
    if (message.type === "PREPARE_DISPATCH_DOWNLOAD") {
        console.log("[Daisy] PREPARE_DISPATCH_DOWNLOAD received, url:", message.url, "quality:", message.youtubeQuality, "forceHLS:", message.forceHLS);
        let pageUrl = sender.tab?.url || message.url || "";
        console.log("[Daisy] pageUrl:", pageUrl);

        const finish = async () => {
            if (pageUrl.includes("youtube.com") || pageUrl.includes("youtu.be")) {
                console.log("[Daisy] YouTube path");
                const cookies = await getYouTubeAuthCookies();
                let cookiePayload = message.cookies || "";
                if (cookies && cookies.length > 0) cookiePayload = formatNetscapeCookies(cookies);
                console.log("[Daisy] calling triggerDownload (YT), quality:", message.youtubeQuality);
                await triggerDownload(message.url, message.filename, sender.tab?.url || "", cookiePayload, message.youtubeQuality, message.forceHLS);
            } else {
                console.log("[Daisy] generic path");
                let cookiePayload = message.cookies || "";
                if (pageUrl.startsWith("http")) {
                    const fetchedCookies = await fetchBaseDomainCookies(pageUrl);
                    cookiePayload = message.cookies || fetchedCookies;
                }
                console.log("[Daisy] calling triggerDownload (generic)");
                await triggerDownload(message.url, message.filename, sender.tab?.url || "", cookiePayload, message.youtubeQuality, message.forceHLS);
            }
            console.log("[Daisy] finish() done");
        };

        finish()
            .then(() => { console.log("[Daisy] sendResponse success"); sendResponse({ success: true }); })
            .catch((e) => { console.error("[Daisy] finish() rejected:", e); sendResponse({ success: false }); });

        return true;
    }
});

async function getHostBrowser() {
    return "safari";
}

async function triggerDownload(url, filename, referer, cookies, youtubeQuality, forceHLS) {
    console.log("[Daisy] triggerDownload() url:", url, "filename:", filename, "quality:", youtubeQuality, "forceHLS:", forceHLS);

    let finalCookies = cookies;
    if (!finalCookies) {
        finalCookies = await fetchBaseDomainCookies(referer || url);
    }

    const extBrowser = await getHostBrowser();
    const payload = JSON.stringify({
        url, filename: filename || "download", cookies: finalCookies || "",
        referer: referer || "", ua: navigator.userAgent, browser: extBrowser,
        youtubeQuality, forceHLS
    });

    console.log("[Daisy] payload:", payload);

    let success = false;
    for (let port = 6840; port <= 6850; port++) {
        try {
            console.log("[Daisy] trying port", port);
            const resp = await fetch(`http://127.0.0.1:${port}/dispatch`, {
                method: "POST", headers: { "Content-Type": "application/json" }, body: payload
            });
            if (resp.ok) {
                console.log("[Daisy] success on port", port);
                success = true;
                break;
            } else {
                console.warn("[Daisy] port", port, "responded not ok:", resp.status);
            }
        } catch (e) {
            console.log("[Daisy] port", port, "failed:", e.message);
        }
    }

    if (!success) {
        console.warn("[Daisy] all ports failed — is Daisy.app running?");
    }
}

_api.webRequest.onHeadersReceived.addListener(
    function(details) {
        if (details.tabId === -1) return;
        const targetMimeTypes = ["video/", "audio/", "mpegurl", "m3u8", "video/mp2t", "application/x-mpegurl", "application/vnd.apple.mpegurl"];
        const isMedia = details.responseHeaders?.some(h =>
            h.name.toLowerCase() === "content-type" && targetMimeTypes.some(m => h.value.toLowerCase().includes(m))
        );
        const urlLower = details.url.toLowerCase();
        const isMediaByUrl = ['.m3u8', '.ts', '.mp4', '.webm', '.mov', '.mkv', '/hls/', '/m3u8', 'manifest.m3u8'].some(p => urlLower.includes(p));

        if (isMedia || isMediaByUrl) {
            _api.tabs.sendMessage(
                details.tabId,
                { type: 'NEW_MEDIA_FOUND', mediaInfo: { url: details.url, frameId: details.frameId } },
                { frameId: 0 }
            ).catch(() => {});

            if (details.frameId !== 0) {
                _api.tabs.sendMessage(
                    details.tabId,
                    { type: 'NEW_MEDIA_FOUND', mediaInfo: { url: details.url, frameId: details.frameId } },
                    { frameId: details.frameId }
                ).catch(() => {});
            }
        }
    },
    { urls: ["<all_urls>"] },
    ["responseHeaders"]
);
